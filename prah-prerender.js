#!/usr/bin/env node
/**
 * prah-prerender.js — bakes the script-rendered blocks of prah-mockup.html
 * back into the file itself.
 *
 * Why: tapping an .html file in a phone's Files app opens a *preview*, and
 * previews do not run scripts. PRÁH renders its cards, hero photo and
 * testimonials from a data model at runtime, so without this step a phone
 * preview shows an empty page.
 *
 * The script loads the page in a real browser, reads the DOM the script
 * produced, and writes that markup between the same container tags. On a
 * normal visit the script re-renders those containers, so the baked copy only
 * ever matters when scripts are off.
 *
 * Run it after changing PROPERTIES, TESTIMONIALS, AGENT or the scene
 * generator:
 *     node prah-prerender.js
 *
 * Needs Playwright's chromium available (npx playwright install chromium).
 */
const path = require("path");
const fs = require("fs");
const { chromium } = require("playwright");

const FILE = path.join(__dirname, "prah-mockup.html");
const MARK =
  "\n      <!-- prerendered: this block is regenerated by the script on load;\n" +
  "           it is baked in so a script-less preview still shows the page -->\n";

/* container open tag -> key of the extracted markup */
const BLOCKS = [
  ['<div class="hero__media" id="heroMedia" aria-hidden="true">', "</div>", "heroMedia"],
  ['<div class="grid-props grid-props--featured" id="featuredGrid">', "</div>", "featuredGrid"],
  ['<div class="grid-props" id="catalogGrid">', "</div>", "catalogGrid"],
  ['<div class="tsm__rail" id="tsmRail">', "</div>", "tsmRail"]
];

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("file://" + FILE);
  await page.waitForTimeout(1500);

  const parts = await page.evaluate(() => {
    /* strip the reveal state the observer added — the baked copy starts fresh */
    const clean = html => html.replace(/ is-in(?=["\s])/g, "").replace(/\sstyle="--d:[^"]*"/g, "");
    const grab = id => clean(document.getElementById(id).innerHTML);
    return {
      heroMedia: grab("heroMedia"),
      featuredGrid: grab("featuredGrid"),
      catalogGrid: grab("catalogGrid"),
      tsmRail: grab("tsmRail"),
      agentImg: clean(document.querySelector("#agentMedia img").outerHTML)
    };
  });
  await browser.close();

  if (errors.length) {
    console.error("Page errors — not writing:\n" + errors.join("\n"));
    process.exit(1);
  }

  let html = fs.readFileSync(FILE, "utf8");

  /* Empty a container before re-filling it. The baked markup contains nested
     <div>s, so the container's own closing tag has to be found by depth. */
  const emptyOut = open => {
    const start = html.indexOf(open);
    if (start < 0) throw new Error("container not found: " + open);
    const from = start + open.length;
    let depth = 1, i = from;
    while (depth > 0) {
      const nextOpen = html.indexOf("<div", i);
      const nextClose = html.indexOf("</div>", i);
      if (nextClose < 0) throw new Error("unbalanced markup after: " + open);
      if (nextOpen >= 0 && nextOpen < nextClose) { depth++; i = nextOpen + 4; }
      else if (--depth === 0) { html = html.slice(0, from) + html.slice(nextClose); }
      else { i = nextClose + 6; }
    }
  };

  for (const [open, , key] of BLOCKS) {
    emptyOut(open);
    html = html.replace(open, open + MARK + parts[key]);
  }

  /* the agent photo is inserted before the badge rather than replacing it */
  const agentOpen = '<div class="agent__media reveal" id="agentMedia">';
  const badge = '<div class="agent__badge">';
  const aStart = html.indexOf(agentOpen) + agentOpen.length;
  const aEnd = html.indexOf(badge, aStart);
  html = html.slice(0, aStart) + MARK + parts.agentImg + "\n          " + html.slice(aEnd);

  fs.writeFileSync(FILE, html);
  console.log("prerendered " + Math.round(html.length / 1024) + " kB");
})();
