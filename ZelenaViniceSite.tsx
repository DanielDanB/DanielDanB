/* Merging — a group Framer has never stored comes through undefined   */
/* ------------------------------------------------------------------ */

function merge<T extends object>(defaults: T, value?: Partial<T> | null): T {
    const out = { ...defaults } as any
    if (!value || typeof value !== "object") return out
    for (const key of Object.keys(value)) {
        const v = (value as any)[key]
        if (v === undefined || v === null) continue
        out[key] = v
    }
    return out
}

/** Arrays: an empty array from the panel is a deliberate "show nothing". */
function list<T>(value: any, fallback: T[]): T[] {
    return Array.isArray(value) ? value : fallback
}

