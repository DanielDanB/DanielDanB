type RGBA = { r: number; g: number; b: number; a: number }

function parseColor(input?: string): RGBA | null {
    if (typeof input !== "string") return null
    const value = input.trim()

    const hex = value.match(/^#([0-9a-f]{3,8})$/i)
    if (hex) {
        let h = hex[1]
        if (h.length === 3 || h.length === 4) {
            h = h
                .split("")
                .map((c) => c + c)
                .join("")
        }
        if (h.length !== 6 && h.length !== 8) return null
        return {
            r: parseInt(h.slice(0, 2), 16),
            g: parseInt(h.slice(2, 4), 16),
            b: parseInt(h.slice(4, 6), 16),
            a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1,
        }
    }

    const rgb = value.match(
        /^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:[\s,/]+([\d.%]+))?\s*\)$/i
    )
    if (rgb) {
        const alpha =
            rgb[4] === undefined
                ? 1
                : rgb[4].endsWith("%")
                  ? parseFloat(rgb[4]) / 100
                  : parseFloat(rgb[4])
        return { r: +rgb[1], g: +rgb[2], b: +rgb[3], a: alpha }
    }
    return null
}

/** Same colour at a different alpha; falls back for Framer design tokens. */
function withAlpha(color: string, alpha: number): string {
    const c = parseColor(color)
    if (!c) {
        return `color-mix(in srgb, ${color} ${Math.round(alpha * 100)}%, transparent)`
    }
    const a = Math.max(0, Math.min(1, c.a * alpha))
    return `rgba(${Math.round(c.r)}, ${Math.round(c.g)}, ${Math.round(c.b)}, ${+a.toFixed(3)})`
}

/** Darken (amount < 0) or lighten (amount > 0) towards black/white. */
function shade(color: string, amount: number): string {
    const c = parseColor(color)
    if (!c) {
        const target = amount < 0 ? "black" : "white"
        return `color-mix(in srgb, ${color} ${Math.round((1 - Math.abs(amount)) * 100)}%, ${target})`
    }
    const t = amount < 0 ? 0 : 255
    const p = Math.abs(amount)
    const mix = (v: number) => Math.round(v + (t - v) * p)
    return `rgb(${mix(c.r)}, ${mix(c.g)}, ${mix(c.b)})`
}

/** Relative luminance, used to pick readable text over a colour. */
function luminance(color: string): number {
    const c = parseColor(color)
    if (!c) return 1
    const ch = [c.r, c.g, c.b].map((v) => {
        const s = v / 255
        return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4)
    })
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]
}

const isLight = (color: string) => luminance(color) > 0.5

