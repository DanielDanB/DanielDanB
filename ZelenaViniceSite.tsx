/** People paste the whole <iframe …> from Share → Embed a map. Take the src. */
function embedSrc(value: string): string {
    const raw = (value || "").trim()
    if (!raw) return ""
    const m = raw.match(/src\s*=\s*["']([^"']+)["']/i)
    return m ? m[1] : raw
}

function mapUrl(loc: any): string {
    if (loc.mapMode === "off") return ""
    if (loc.mapMode === "embed") return embedSrc(loc.mapEmbed)
    const q = (loc.mapQuery || loc.address || "").replace(/\n+/g, ", ").trim()
    if (!q) return ""
    const zoom = Math.max(1, Math.min(21, Number(loc.mapZoom) || 16))
    const lang = (loc.mapLang || "en").trim()
    return `https://www.google.com/maps?q=${encodeURIComponent(q)}&z=${zoom}&hl=${encodeURIComponent(lang)}&output=embed`
}

function directionsUrl(loc: any): string {
    const q = (loc.mapQuery || loc.address || "").replace(/\n+/g, ", ").trim()
    if (!q) return ""
    return `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(q)}`
}

const lines = (value?: string) => String(value || "").split("\n")

const paragraphs = (value?: string) =>
    String(value || "")
        .split(/\n\s*\n/)
        .map((p) => p.trim())
        .filter(Boolean)

