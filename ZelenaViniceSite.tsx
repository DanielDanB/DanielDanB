/**
 * A theme is the base; anything picked by hand layers on top of it. The
 * override pickers are `optional`, so an untouched one arrives as undefined
 * and the theme keeps its colour — which is what lets someone take Cellar and
 * change only the accent. An empty string counts as unset too, so this holds
 * whichever way Framer reports a disabled control.
 */
function resolveColors(input: any) {
    const stored = input && typeof input === "object" ? input : {}
    const preset = stored.preset || DEFAULTS.colors.preset
    const base: any = {
        ...DEFAULTS.colors,
        ...(THEMES[preset] || THEMES[DEFAULTS.colors.preset]),
        preset,
    }
    if (stored.glow !== undefined && stored.glow !== null) base.glow = stored.glow
    if (stored.resetToTheme === true) return base

    for (const key of COLOR_KEYS) {
        const value = stored[key]
        if (typeof value === "string" && value.trim()) base[key] = value
    }
    return base
}

