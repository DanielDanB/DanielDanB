const isImageSource = (value?: string) =>
    typeof value === "string" &&
    /^(https?:|data:|blob:|\/\/|\/)/i.test(value.trim())

/**
 * One icon slot that accepts three kinds of value:
 *   · a Phosphor name  ("fork-knife", "ph-fork-knife")  → inline SVG
 *   · an image or data URL                              → <img>
 *   · anything else ("🍝")                              → rendered as text
 */
function Icon({
    name,
    size,
    className,
}: {
    name?: string
    size?: number | string
    className?: string
}) {
    const raw = (name || "").trim()
    if (!raw) return null

    if (isImageSource(raw)) {
        return (
            <img
                className={`zv-icon-img${className ? " " + className : ""}`}
                src={raw}
                alt=""
                aria-hidden="true"
                style={size ? { width: size, height: size } : undefined}
            />
        )
    }

    const key = raw.replace(/^ph\s+/, "").replace(/^ph-/, "")
    const d = ICON_PATHS[key]
    if (!d) {
        return (
            <span
                className={`zv-icon-text${className ? " " + className : ""}`}
                aria-hidden="true"
                style={size ? { fontSize: size, lineHeight: 1 } : undefined}
            >
                {raw}
            </span>
        )
    }

    return (
        <svg
            className={`zv-icon${className ? " " + className : ""}`}
            viewBox="0 0 1024 1024"
            fill="currentColor"
            focusable="false"
            aria-hidden="true"
            style={size ? { width: size, height: size } : undefined}
        >
            <g transform="translate(0,960) scale(1,-1)">
                <path d={d} />
            </g>
        </svg>
    )
}

