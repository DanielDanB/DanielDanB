const useIsomorphicLayoutEffect =
    typeof document !== "undefined" ? React.useLayoutEffect : React.useEffect

/** Injects the stylesheet once and keeps its text in sync. */
function useStyleSheet(css: string, fontsUrl?: string) {
    useIsomorphicLayoutEffect(() => {
        let el = document.getElementById(STYLE_ID) as HTMLStyleElement | null
        if (!el) {
            el = document.createElement("style")
            el.id = STYLE_ID
            document.head.appendChild(el)
        }
        // @import has to come first in a sheet, so it is prepended here rather
        // than living inside the CSS constant.
        el.textContent = (fontsUrl ? `@import url('${fontsUrl}');\n` : "") + css
    }, [css, fontsUrl])
}

/** Breakpoint classes from the component's own width, not the window's. */
function useWidthClass(ref: React.RefObject<HTMLElement>) {
    const [widthClass, setWidthClass] = React.useState("")

    useIsomorphicLayoutEffect(() => {
        const el = ref.current
        if (!el) return

        const apply = (width: number) => {
            if (!width) return
            const classes: string[] = []
            if (width <= 1024) classes.push("w-md")
            if (width <= 780) classes.push("w-sm")
            if (width <= 520) classes.push("w-xs")
            const next = classes.join(" ")
            setWidthClass((prev) => (prev === next ? prev : next))
        }

        apply(el.offsetWidth)
        if (typeof ResizeObserver === "undefined") {
            const onResize = () => apply(el.offsetWidth)
            window.addEventListener("resize", onResize)
            return () => window.removeEventListener("resize", onResize)
        }
        const observer = new ResizeObserver((entries) =>
            apply(entries[0].contentRect.width)
        )
        observer.observe(el)
        return () => observer.disconnect()
    }, [ref])

    return widthClass
}

/**
 * Mount-then-animate. A panel parked off-screen at right:-100% is not clipped
 * by an ancestor — fixed elements escape overflow — and inside Framer's
 * transformed page wrapper it becomes real horizontal overflow on the
 * published site. So it exists only while open, and slides with a transform.
 */
function useSlideIn(open: boolean, duration = 400) {
    const [mounted, setMounted] = React.useState(open)
    const [slidIn, setSlidIn] = React.useState(false)

    React.useEffect(() => {
        if (open) {
            setMounted(true)
            // Two frames: the browser has to paint the closed state before the
            // class change can transition.
            const a = requestAnimationFrame(() =>
                requestAnimationFrame(() => setSlidIn(true))
            )
            return () => cancelAnimationFrame(a)
        }
        setSlidIn(false)
        const t = setTimeout(() => setMounted(false), duration)
        return () => clearTimeout(t)
    }, [open, duration])

    return { mounted, slidIn }
}

/**
 * Framer's published page sits inside a transformed wrapper, and a transform
 * makes its element the containing block for fixed-position descendants — so
 * a modal at top:50% lands halfway down the whole page instead of the
 * viewport. Rendering overlays into document.body sidesteps that; the wrapper
 * keeps the root class and the custom properties so the scoped CSS still
 * applies.
 */
function usePortalHost() {
    const [host, setHost] = React.useState<HTMLElement | null>(null)
    React.useEffect(() => {
        if (typeof document === "undefined") return
        const el = document.createElement("div")
        el.setAttribute("data-zv-overlay", "")
        document.body.appendChild(el)
        setHost(el)
        return () => {
            el.remove()
        }
    }, [])
    return host
}

/** Escape closes whatever is open. */
function useEscape(active: boolean, close: () => void) {
    React.useEffect(() => {
        if (!active) return
        const onKey = (e: KeyboardEvent) => {
            if (e.key === "Escape") close()
        }
        window.addEventListener("keydown", onKey)
        return () => window.removeEventListener("keydown", onKey)
    }, [active, close])
}

