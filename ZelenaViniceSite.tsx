const SECTIONS = ["top", "menu", "about", "gallery", "location", "reserve"]

/** "#menu", "index.html#menu" and "/#menu" all mean the same section here. */
function anchorKey(href?: string): string | null {
    if (typeof href !== "string") return null
    const hash = href.indexOf("#")
    if (hash === -1) return null
    const key = href.slice(hash + 1).trim()
    return SECTIONS.includes(key) ? key : key ? key : null
}

function scrollTo(root: HTMLElement | null, key: string) {
    if (!root) return
    if (key === "top") {
        root.scrollIntoView({ behavior: "smooth", block: "start" })
        return
    }
    const el = root.querySelector(`[data-zv-section="${key}"]`)
    if (el) (el as HTMLElement).scrollIntoView({ behavior: "smooth", block: "start" })
}

/**
 * A link that scrolls inside the component when it points at one of its own
 * sections, and behaves like an ordinary link otherwise.
 */
function SmartLink({
    href,
    rootRef,
    className,
    children,
    onNavigate,
    ...rest
}: {
    href?: string
    rootRef: React.RefObject<HTMLElement>
    className?: string
    children: React.ReactNode
    onNavigate?: () => void
    [key: string]: any
}) {
    const key = anchorKey(href)
    const internal = key !== null && !/^https?:/i.test(href || "")

    const onClick = (e: React.MouseEvent) => {
        if (!internal) return
        e.preventDefault()
        onNavigate?.()
        scrollTo(rootRef.current, key as string)
    }

    return (
        <a className={className} href={href || "#"} onClick={onClick} {...rest}>
            {children}
        </a>
    )
}

